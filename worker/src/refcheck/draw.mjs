/** Writes `text` (upper-cased) at (x, y) in `color`, each font pixel `scale` pixels. */
export function text(img, x, y, str, color = [235, 235, 235], scale = 1) {
  let cx = x
  for (const ch of String(str).toUpperCase()) {
    const g = GLYPHS[ch] ?? GLYPHS['?']
    const rows = g.split(' ')
    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < 5; c++) {
        if (rows[r][c] !== '1') continue
        for (let j = 0; j < scale; j++) for (let i = 0; i < scale; i++) setPixel(img, cx + c * scale + i, y + r * scale + j, color)
      }
    }
    cx += 6 * scale
  }
  return cx
}

function setPixel({ width, height, rgba }, x, y, [r, g, b]) {
  if (x < 0 || y < 0 || x >= width || y >= height) return
  const o = (y * width + x) * 4
  rgba[o] = r; rgba[o + 1] = g; rgba[o + 2] = b; rgba[o + 3] = 255
}

/** Copies `src` into `dst` with its top-left at (x, y), blending by the source's alpha over what is there. */
export function paste(dst, src, x, y) {
  for (let j = 0; j < src.height; j++) {
    const dy = y + j
    if (dy < 0 || dy >= dst.height) continue
    for (let i = 0; i < src.width; i++) {
      const dx = x + i
      if (dx < 0 || dx >= dst.width) continue
      const s = (j * src.width + i) * 4, d = (dy * dst.width + dx) * 4
      const a = src.rgba[s + 3] / 255
      for (let k = 0; k < 3; k++) dst.rgba[d + k] = Math.round(src.rgba[s + k] * a + dst.rgba[d + k] * (1 - a))
      dst.rgba[d + 3] = 255
    }
  }
}

/** A filled rectangle. */
export function rect(img, x, y, w, h, color) {
  for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) setPixel(img, x + i, y + j, color)
}

/** The edge of `mask` (on the image's grid) drawn over the image. */
export function outline(img, mask, color) {
  const { width: w, height: h } = img
  for (let y = 1; y < h - 1; y++) {
    for (let x = 1; x < w - 1; x++) {
      const i = y * w + x
      if (mask[i] && (!mask[i - 1] || !mask[i + 1] || !mask[i - w] || !mask[i + w])) setPixel(img, x, y, color)
    }
  }
}
